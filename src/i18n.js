let currentLang = 'zh'; // 'zh' or 'en'
const translatedNodes = new WeakMap();

// Some nodes are created dynamically, so we observe the DOM
const observer = new MutationObserver((mutations) => {
  if (currentLang === 'en') {
    observer.disconnect();
    mutations.forEach(mutation => {
      if (mutation.type === 'childList') {
        mutation.addedNodes.forEach(node => walkNodeTree(node, translateNode));
      } else if (mutation.type === 'characterData') {
        // If the original text changes, update our stored original and translate
        const textNode = mutation.target;
        translatedNodes.set(textNode, textNode.textContent); // Store new Chinese text
        translateNode(textNode); // Translate it to English immediately
      }
    });
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  }
});

function walkNodeTree(node, callback) {
  if (node.nodeType === Node.TEXT_NODE) {
    callback(node);
  } else if (node.nodeType === Node.ELEMENT_NODE) {
    // Also translate placeholders
    if (node.placeholder) {
      if (translatedNodes.has(node) && translatedNodes.get(node).placeholder) {
        node.placeholder = currentLang === 'en' ? dictionary[translatedNodes.get(node).placeholder] : translatedNodes.get(node).placeholder;
      } else if (dictionary[node.placeholder]) {
        let saved = translatedNodes.get(node) || {};
        saved.placeholder = node.placeholder;
        translatedNodes.set(node, saved);
        if (currentLang === 'en') node.placeholder = dictionary[node.placeholder];
      }
    }
    
    // Also title attributes
    if (node.title) {
      if (translatedNodes.has(node) && translatedNodes.get(node).title) {
        node.title = currentLang === 'en' ? dictionary[translatedNodes.get(node).title] : translatedNodes.get(node).title;
      } else if (dictionary[node.title]) {
        let saved = translatedNodes.get(node) || {};
        saved.title = node.title;
        translatedNodes.set(node, saved);
        if (currentLang === 'en') node.title = dictionary[node.title];
      }
    }
    
    // Skip script/style tags
    if (node.tagName !== 'SCRIPT' && node.tagName !== 'STYLE') {
      node.childNodes.forEach(child => walkNodeTree(child, callback));
    }
  }
}

function translateNode(textNode) {
  let originalText = translatedNodes.get(textNode);
  if (!originalText) {
    originalText = textNode.textContent;
    if (!originalText.trim()) return;
    translatedNodes.set(textNode, originalText);
  }

  if (currentLang === 'en') {
    // Simple replacement
    let newText = originalText;
    
    // Sort dictionary keys by length descending to replace longer phrases first
    const keys = Object.keys(dictionary).sort((a, b) => b.length - a.length);
    for (const key of keys) {
      if (newText.includes(key)) {
        newText = newText.split(key).join(dictionary[key]);
      }
    }
    textNode.textContent = newText;
  } else {
    textNode.textContent = originalText;
  }
}

export function initI18n() {
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
}

export function toggleLanguage() {
  currentLang = currentLang === 'zh' ? 'en' : 'zh';
  observer.disconnect();
  walkNodeTree(document.body, translateNode);
  
  // Update toggle button text if exists
  const btn = document.getElementById("langToggleBtn");
  if (btn) {
      btn.innerHTML = `🌐 ${currentLang === 'zh' ? '中/EN' : 'EN/中'}`;
  }
  
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  return currentLang;
}
